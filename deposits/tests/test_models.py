"""Model-level guarantees: Islamic labelling is schema-enforced."""

import pytest

from django.core.exceptions import ValidationError
from django.db import IntegrityError, transaction

from deposits.models import DepositProduct


@pytest.mark.django_db
def test_islamic_product_cannot_be_labelled_interest():
    product = DepositProduct(
        institution_name="Test Islamic Bank",
        kind="fdr",
        name="Mudaraba Test",
        is_islamic=True,
        rate_type="interest",
    )
    with pytest.raises(ValidationError):
        product.clean()
    with transaction.atomic(), pytest.raises(IntegrityError):
        product.save()


@pytest.mark.django_db
def test_slug_autogenerated_and_institution_display():
    product = DepositProduct.objects.create(
        institution_name="National Savings Directorate (Sanchayapatra)",
        kind="scheme",
        name="Paribar Sanchayapatra",
        is_benchmark=True,
    )
    assert product.slug.startswith("national-savings-directorate")
    assert (
        product.institution_display_name == "National Savings Directorate (Sanchayapatra)"
    )
    assert product.is_public is False  # draft until verified
